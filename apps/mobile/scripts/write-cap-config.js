/**
 * Writes apps/mobile/capacitor.config.ts with the correct dev server URL.
 * Usage: node scripts/write-cap-config.js [--emulator] [--path=/ar/patient]
 */
const fs = require("fs");
const os = require("os");
const path = require("path");

const emulator = process.argv.includes("--emulator");
const pathArg = process.argv.find((a) => a.startsWith("--path="));
const startPath = pathArg ? pathArg.slice("--path=".length) : "/ar/patient";

function getLanIp() {
  const candidates = [];
  for (const nets of Object.values(os.networkInterfaces())) {
    for (const net of nets ?? []) {
      const v4 = net.family === "IPv4" || net.family === 4;
      if (!v4 || net.internal) continue;
      const a = net.address;
      // Skip typical virtual / link-local adapters on Windows (VirtualBox, Hyper-V, etc.)
      if (a.startsWith("169.254.")) continue;
      if (a.startsWith("192.168.56.")) continue;
      candidates.push(a);
    }
  }
  const preferred = candidates.find((a) => /^192\.168\.(0|1|2|3|4|5|10|20|31)\./.test(a));
  return preferred ?? candidates[0] ?? "127.0.0.1";
}

const host = emulator ? "10.0.2.2" : getLanIp();
const port = process.env.CLINIC_PORT || "3000";
const serverUrl = process.env.CAP_SERVER_URL || `http://${host}:${port}${startPath}`;

const outPath = path.join(__dirname, "..", "capacitor.config.ts");
const contents = `import type { CapacitorConfig } from "@capacitor/cli";

/** Auto-generated by scripts/write-cap-config.js — do not edit server.url by hand for preview. */
const config: CapacitorConfig = {
  appId: "iq.clinicpro.app",
  appName: "ClinicPro",
  webDir: "www",
  server: {
    url: ${JSON.stringify(serverUrl)},
    cleartext: true,
    androidScheme: "http",
  },
  android: {
    allowMixedContent: true,
  },
  plugins: {
    SplashScreen: {
      launchShowDuration: 1200,
      backgroundColor: "#060912",
      showSpinner: false,
    },
    StatusBar: {
      style: "DARK",
      backgroundColor: "#060912",
    },
  },
};

export default config;
`;

fs.writeFileSync(outPath, contents, "utf8");
console.log(`Capacitor server URL → ${serverUrl}`);
if (!emulator && host === "127.0.0.1") {
  console.warn("Warning: no LAN IP found — use --emulator or set CAP_SERVER_URL for a physical phone.");
}
