import "dotenv/config";
import fs from "fs";
import path from "path";
import { defineConfig } from "prisma/config";

const root = path.resolve(__dirname, "../..");
for (const name of [".env.local", ".env"]) {
  const file = path.join(root, name);
  if (!fs.existsSync(file)) continue;
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 1) continue;
    const key = trimmed.slice(0, eq).trim();
    if (process.env[key] !== undefined) continue;
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    process.env[key] = value;
  }
}

const defaultUrl = `file:${path.join(__dirname, "prisma", "dev.db")}`;
// Direct connection for schema changes. The app runtime keeps the pooled DATABASE_URL.
const migrateUrl = process.env.DATABASE_URL_UNPOOLED ?? process.env.DATABASE_URL ?? defaultUrl;

export default defineConfig({
  schema: "prisma/schema.prisma",
  migrations: {
    path: "prisma/migrations",
  },
  datasource: {
    url: migrateUrl,
  },
});
